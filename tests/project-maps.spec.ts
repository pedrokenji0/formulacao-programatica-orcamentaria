test('exportação de revisão inclui original e proposta do mapa único', async ({ page }) => {
  await open(page); await resourceButton(page).click();
  await page.getByLabel('Texto do componente', { exact: true }).fill('Recurso reformulado para comparação');
  await page.getByRole('button', { name: 'Concluir ficha', exact: true }).click();
  await page.getByRole('button', { name: 'Revisão do Planejamento', exact: true }).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar revisão qualitativa', exact: true }).click();
  const path = await (await downloaded).path();
  const payload = JSON.parse(readFileSync(path!, 'utf8'));
  expect(payload.projectMaps).toHaveLength(1);
  expect(payload.projectMaps[0].original.components).toHaveLength(37);
  expect(payload.projectMaps[0].proposal.components.find((item: { text: string }) => item.text === 'Recurso reformulado para comparação')).toBeTruthy();
  expect(payload.projectMaps[0].proposal.indicators).toHaveLength(12);
  expect(payload.projectMaps[0].proposal.actionIds).toEqual(['ppo-acao-125-1221-1082', 'ppo-acao-125-2461-4528']);
});

test('catálogo de UOs elimina sobras persistidas e zeros à esquerda', async ({ page }) => {
  await open(page);
  await page.locator('.profile-sel select').selectOption('Gestor Setorial');
  await page.waitForFunction(() => !!localStorage.getItem('fpo-state-v2'));
  await page.evaluate(() => {
    const saved = JSON.parse(localStorage.getItem('fpo-state-v2')!);
    saved.values.lists.unidades.push('1481 — Fundação de Arte de Ouro Preto', '1261 — Secretaria de Estado de Educação (SEE)', '1451 — Sec. de Justiça e Segurança Pública (SEJUSP)', '1501 — Secretaria de Planejamento e Gestão (SEPLAG)', '1501001 — Central Geral');
    localStorage.setItem('fpo-state-v2', JSON.stringify(saved));
  });
  await page.reload();
  const select = page.getByTitle('Unidade', { exact: true });
  await expect(select).toBeVisible();
  const labels = await select.locator('option').allTextContents();
  expect(labels.some((label) => /^0\d/.test(label))).toBe(false);
  expect(labels.some((label) => /^(4741|4441|4451|1991)\s/.test(label))).toBe(false);
  expect(labels.some((label) => label.includes('Central Geral'))).toBe(false);
  expect(labels.some((label) => /1481.*Ouro Preto/.test(label))).toBe(false);
  expect(labels.filter((label) => /^1261\s/.test(label))).toHaveLength(1);
  expect(labels.filter((label) => /^1451\s/.test(label))).toHaveLength(1);
  expect(labels.filter((label) => /^1501\s/.test(label))).toHaveLength(1);
  expect(labels.find((label) => /^2171\s/.test(label))).toContain('OURO PRETO');
});

test('novo projeto usa editor Reurb vazio, persiste e limpa abas independentemente', async ({ page }) => {
  await open(page);
  await page.getByRole('button', { name: 'Criar mapa do zero', exact: true }).click();
  await page.getByLabel('Nome do projeto ou processo', { exact: true }).fill('Política transversal — teste');
  const participants = page.getByRole('dialog').locator('.project-map-check');
  await participants.first().getByRole('checkbox').check();
  await participants.nth(1).getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Criar mapas vazios', exact: true }).click();
  await expect(page.locator('.project-map-workspace')).toContainText('Política transversal — teste');
  await expect(page.locator('.project-map-node')).toHaveCount(0);
  await expect(page.locator('.project-map-column')).toHaveCount(7);
  await page.getByRole('region', { name: 'MaPR do projeto', exact: true }).locator('.stage-recurso').getByRole('button', { name: 'Adicionar', exact: true }).click();
  await page.getByLabel('Texto do componente', { exact: true }).fill('Equipe técnica do projeto novo');
  await page.getByRole('dialog').getByRole('checkbox').first().check();
  await page.getByRole('button', { name: 'Concluir ficha', exact: true }).click();
  await page.getByRole('button', { name: 'Mapa de Indicadores', exact: true }).click();
  await expect(page.locator('.indicator-node')).toHaveCount(0);
  await page.locator('.stage-recurso').getByRole('button', { name: 'Adicionar indicador', exact: true }).click();
  await page.getByLabel('Nome do indicador', { exact: true }).fill('Pessoas mobilizadas');
  await page.getByLabel('Fórmula de cálculo', { exact: true }).fill('Contagem de pessoas');
  await page.getByRole('dialog').getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Concluir ficha', exact: true }).click();
  await page.getByRole('button', { name: 'Salvar proposta do mapa', exact: true }).click();
  const mapId = await page.locator('.project-map-workspace').getAttribute('data-map-id');
  await page.reload(); await mapButton(page).click();
  await page.getByLabel('Mapa em edição', { exact: true }).selectOption(mapId!);
  await expect(page.locator('.project-map-workspace')).toContainText('Equipe técnica do projeto novo');
  await page.getByRole('button', { name: 'Limpar MaPR', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar limpeza', exact: true }).click();
  await expect(page.locator('.project-map-node')).toHaveCount(0);
  await page.getByRole('button', { name: 'Mapa de Indicadores', exact: true }).click();
  await expect(page.locator('.indicator-node')).toContainText('Pessoas mobilizadas');
  await page.locator('.profile-sel select').selectOption('Leitor');
  await expect(page.getByRole('button', { name: 'Limpar indicadores', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Criar mapa do zero', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Abrir indicador Pessoas mobilizadas', exact: true }).click();
  await expect(page.getByLabel('Nome do indicador', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Concluir ficha', exact: true }).click();
  await page.getByLabel('Mapa em edição', { exact: true }).selectOption('mapa-minas-reurb');
  await page.getByRole('button', { name: 'MaPR — Processos e Resultados', exact: true }).click();
  await expect(page.locator('.project-map-node')).toHaveCount(37);
});
