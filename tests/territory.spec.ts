test('recursos exportam localizadores sem repetir total regional em municípios', async ({ page }) => {
  await open(page);
  await page.getByRole('button', { name: 'Recursos orçamentários', exact: true }).click();
  await page.getByRole('button', { name: 'Ver recursos da ação 4528', exact: true }).click();
  await page.getByLabel('Regionalização do mapa', { exact: true }).selectOption('fjp-health-micro');
  await expect(page.getByRole('region', { name: 'Resumo dos recursos orçamentários' })).toContainText('Recursos regionais permanecem no recorte original');
  await page.getByRole('button', { name: 'Ver recursos por região de origem', exact: true }).click();
  await expect(page.getByLabel('Regionalização do mapa', { exact: true })).toHaveValue('ibge-intermediate');
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar recursos em CSV', exact: true }).click();
  const download = await pending;
  expect(download.suggestedFilename()).toBe('recursos-acao-4528-2026.csv');
  const stream = await download.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv.trim().split('\n')).toHaveLength(2);
  expect(csv).toContain('"intermediate";"3105"');
  expect(csv).toContain('"W44490";"4528";"2461";"2026"');
  expect(csv).toContain('"16545637"');
  expect(csv).not.toContain('"3131307"');
});

