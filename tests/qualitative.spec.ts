import { test, expect, type Page } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';

const reference = JSON.parse(gunzipSync(readFileSync('public/data/planning.json.gz')).toString('utf8'));
const program125 = reference.programs.find((record: { codigo: string }) => Number(record.codigo) === 125);
const sede = reference.actions.find((record: { id: string }) => record.id === 'ppo-acao-125-1221-1082');
const armva = reference.actions.find((record: { id: string }) => record.id === 'ppo-acao-125-2461-4528');
const localizer = reference.localizers.find((record: { actionId: string }) => record.actionId === sede.id);
const TERRITORY_FIELDS = ['Código da Região Geográfica Intermediária', 'Região Geográfica Intermediária', 'Código do Município IBGE', 'Código do Município Sigplan', 'Município'];
const button = async (page: Page, name: string) => page.getByRole('button', { name, exact: true }).click();
const closeWindow = async (page: Page) => page.getByRole('dialog').getByRole('button', { name: 'Fechar janela', exact: true }).click();
const openSection = async (page: Page, name: string) => button(page, `Abrir ${name}`);
const open = async (page: Page) => { await page.goto('./'); await expect(page.getByLabel('Programa ativo', { exact: true })).toBeVisible(); };
const selectAction = async (page: Page, action: typeof sede) => {
  const label = `${action.codigo || 'Sem código oficial'} · UO ${action.codigoUnidadeOrcamentaria || 'não informada'} · ${action.nome || 'Ação em rascunho'}`;
  await page.getByRole('combobox', { name: 'Ação', exact: true }).fill(label);
  await page.getByRole('option', { name: label, exact: true }).click();
};
const choice = (fields: Record<string, string>, names: string[]) => JSON.stringify(Object.fromEntries(names.map((name) => [name, fields[name] || ''])));
const choiceLabel = (value: string) => Object.values(JSON.parse(value)).filter(Boolean).join(' — ');
const chooseCatalog = async (page: Page, label: string, value: string) => {
  const text = choiceLabel(value);
  await page.getByRole('combobox', { name: label, exact: true }).fill(text);
  await page.getByRole('option', { name: text, exact: true }).click();
};
const stored = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fpo-state-v2') || '{}'));

